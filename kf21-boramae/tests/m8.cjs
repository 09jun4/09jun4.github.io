// 마일스톤 8 검증: 실제 클릭·키 입력으로 메뉴 → 미션 선택 → 브리핑 → 플레이 → 일시정지 → 결과 → 다음 미션까지 따라가며 캡처한다.
const { startServer, launch, openGame, shot, sleep } = require('./lib/harness.cjs');
(async () => {
  const { server, origin } = await startServer();
  const browser = await launch();
  const { page, errors } = await openGame(browser, origin);
  const d = (fn, a) => page.evaluate(fn, a);
  const st = () => d(() => window.__debug.state());
  const log = {};
  await sleep(900);
  await shot(page, 'm8-menu');
  log.menuButtons = await page.$$eval('.menu-buttons .btn', (b) => b.map((x) => x.textContent.trim()));
  await page.click('.menu [data-act="settings"]'); await sleep(200);
  await shot(page, 'm8-settings');
  await page.keyboard.press('Escape'); await sleep(200);
  await page.click('[data-act="start"]'); await sleep(800);
  await shot(page, 'm8-select');
  log.locked = await page.$$eval('.mission-row', (r) => r.map((x) => x.classList.contains('locked')));
  await page.click('.mission-row[data-id="m2"]'); await sleep(150);
  log.m2BriefDisabled = await page.$eval('[data-act="brief"]', (b) => b.disabled);
  await page.click('.mission-row[data-id="m1"]'); await sleep(150);
  await page.click('[data-act="brief"]'); await sleep(800);
  await shot(page, 'm8-briefing');
  await page.click('[data-act="launch"]'); await sleep(900);
  log.playing = (await st()).state;
  const t1 = (await st()).tick;
  await page.keyboard.press('Escape'); await sleep(400);
  log.paused = (await st()).state;
  await shot(page, 'm8-pause');
  const a = await st(); await sleep(700); const b = await st();
  log.timeFrozenWhilePaused = a.stats.time === b.stats.time;
  await page.keyboard.press('Escape'); await sleep(200);
  log.resumed = (await st()).state;
  // 창 포커스를 잃으면 자동 일시정지
  await d(() => window.dispatchEvent(new Event('blur'))); await sleep(200);
  log.autoPauseOnBlur = (await st()).state;
  await page.click('.pause [data-act="restart"]'); await sleep(900);
  const r = await st();
  log.restarted = { state: r.state, time: r.stats.time < 1.5 };
  await d(() => window.__debug.skipMission(true)); await sleep(1800);
  log.afterClear = (await st()).state;
  await shot(page, 'm8-result-ok');
  log.resultButtons = await page.$$eval('.result .card-actions .btn', (x) => x.map((q) => q.textContent.trim()));
  await page.click('[data-act="next"]'); await sleep(800);
  log.nextBriefing = await page.$eval('.brief-title', (x) => x.textContent.trim());
  await page.click('[data-act="launch"]'); await sleep(900);
  await d(() => window.__debug.skipMission(false)); await sleep(2400);
  await shot(page, 'm8-result-fail');
  log.failButtons = await page.$$eval('.result .card-actions .btn', (x) => x.map((q) => q.textContent.trim()));
  await page.click('.result [data-act="menu"]'); await sleep(900);
  log.backToMenu = (await st()).state;
  await page.click('[data-act="start"]'); await sleep(800);
  log.unlockedAfter = await page.$$eval('.mission-row', (r) => r.map((x) => x.classList.contains('locked')));
  await shot(page, 'm8-select-after');
  void t1;
  console.log(JSON.stringify({ log, errors }, null, 1));
  await browser.close(); server.close();
})();
